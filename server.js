    const SHEETDB_URL = env.SHEETDB_URL;
    if (!SHEETDB_URL) {
        console.warn('⚠️ SHEETDB_URL לא הוגדר - ציונים ייבדקו אך לא יישמרו בגיליון.');
    }

    // 🔒 חומת תשלום + התחברות עם Google
